function dateFromOffset(offset: number): string {
  const base = Date.UTC(2024, 3, 13);
  return new Date(base - offset * 86_400_000).toISOString().slice(0, 10);
}

function generatedStatus(index: number): CustomerStatus {
  if (index < 54) return "won";
  if (index < 78) return "lost";
  return (["intent", "following", "pending"] as const)[(index - 78) % 3];
}

